// Packs jflap/levels/*.jff into js/game/jflap_levels.js so index.html also works by double-click (browsers can't fetch local files).
// Edit a level in JFLAP -> save over its .jff -> run:  node tools/build-levels.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'jflap', 'levels');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.jff')).sort();
const body = files.map((f) => `  ${JSON.stringify(f.replace(/\.jff$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))},`).join('\n');
fs.writeFileSync(path.join(__dirname, '..', 'js', 'game', 'jflap_levels.js'),
`/* GENERATED by tools/build-levels.js from jflap/levels/*.jff — do not edit by hand.
 * Every level's reference machine is a real JFLAP file; this bundle just lets the game read them offline. */
(function () {
  const AM = (globalThis.AM = globalThis.AM || {});
  const G = (AM.G = AM.G || {});
  G.JFF = {
${body}
  };
})();
`);
console.log(`packed ${files.length} JFLAP level files`);
